"""Acrobot-v1 family with a frozen dense upright-height reward.

Not CartPole and not Pendulum. Gymnasium -1/step and goal termination are not
used for the primary. H=3 CartPole and Pendulum FiLM weights are not transferred.
"""
from __future__ import annotations

from nexus.tasks.spec import TaskSpec

ACROBOT_OBS_DIM = 6
ACROBOT_N_ACTIONS = 3
ACROBOT_MAX_STEPS = 200


def _acrobot(task_id: str, split: str, notes: str, **params: float) -> TaskSpec:
    return TaskSpec(
        task_id=task_id,
        family="acrobot",
        gym_id="Acrobot-v1",
        obs_dim=ACROBOT_OBS_DIM,
        n_actions=ACROBOT_N_ACTIONS,
        params=params,
        reward_scale=1.0,
        train_split=split,
        notes=notes,
    )


def acrobot_default() -> TaskSpec:
    return _acrobot(
        "acrobot_default",
        "source",
        "Source training task. Dense upright height, 200-step TimeLimit, no goal termination.",
        LINK_MASS_1=1.0,
        LINK_MASS_2=1.0,
        LINK_LENGTH_1=1.0,
    )


def acrobot_physics_key(spec: TaskSpec) -> tuple[float, float, float]:
    p = spec.params
    return (
        round(float(p["LINK_MASS_1"]), 4),
        round(float(p["LINK_MASS_2"]), 4),
        round(float(p["LINK_LENGTH_1"]), 4),
    )


def acrobot_lookahead_development() -> tuple[TaskSpec, ...]:
    """Unused Acrobot physics for lookahead versus frozen H=16.

    Generated by locked rule `acrobot_lookahead_dev_v1`. Rejects the default
    source (1,1,1). Not a reuse of CartPole or Pendulum splits.
    """
    rows = ((0.95, 1.2, 0.8), (1.25, 1.35, 0.95), (0.75, 1.4, 1.4))
    return tuple(
        _acrobot(
            f"acrobot_look_dev{i}",
            "lookahead_dev",
            f"Lookahead versus H=16 development masses/length {row}.",
            LINK_MASS_1=row[0],
            LINK_MASS_2=row[1],
            LINK_LENGTH_1=row[2],
        )
        for i, row in enumerate(rows)
    )


def acrobot_lookahead_confirmation() -> tuple[TaskSpec, ...]:
    """Unused Acrobot physics for lookahead versus frozen H=16 transfer.

    Rule `acrobot_lookahead_confirm_v1` rejects the source and the development
    draw. H=16, candidates, and dense height are not retuned.
    """
    rows = ((0.75, 0.6, 0.95), (1.3, 1.4, 1.4), (1.15, 0.85, 0.6))
    return tuple(
        _acrobot(
            f"acrobot_look_cf{i}",
            "lookahead_confirm",
            f"Lookahead versus H=16 confirmation masses/length {row}.",
            LINK_MASS_1=row[0],
            LINK_MASS_2=row[1],
            LINK_LENGTH_1=row[2],
        )
        for i, row in enumerate(rows)
    )
