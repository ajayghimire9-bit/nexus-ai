"""MountainCar-v0 family with a frozen dense valley-height reward.

Not Pendulum, CartPole, or Acrobot. Gymnasium -1/step and goal termination
are not used for the primary. H=3 CartPole and Pendulum FiLM are not transferred.
"""
from __future__ import annotations

from nexus.tasks.spec import TaskSpec

MOUNTAINCAR_OBS_DIM = 2
MOUNTAINCAR_N_ACTIONS = 3
MOUNTAINCAR_MAX_STEPS = 200


def _mountaincar(task_id: str, split: str, notes: str, **params: float) -> TaskSpec:
    return TaskSpec(
        task_id=task_id,
        family="mountaincar",
        gym_id="MountainCar-v0",
        obs_dim=MOUNTAINCAR_OBS_DIM,
        n_actions=MOUNTAINCAR_N_ACTIONS,
        params=params,
        reward_scale=1.0,
        train_split=split,
        notes=notes,
    )


def mountaincar_default() -> TaskSpec:
    return _mountaincar(
        "mountaincar_default",
        "source",
        "Source training task. Dense valley height, 200-step TimeLimit, no goal termination.",
        gravity=0.0025,
        force=0.001,
        max_speed=0.07,
    )


def mountaincar_physics_key(spec: TaskSpec) -> tuple[float, float, float]:
    p = spec.params
    return (
        round(float(p["gravity"]), 4),
        round(float(p["force"]), 4),
        round(float(p["max_speed"]), 3),
    )


def mountaincar_lookahead_development() -> tuple[TaskSpec, ...]:
    """Unused MountainCar physics for lookahead versus frozen H=16.

    Generated by locked rule `mountaincar_lookahead_dev_v1`. Rejects the default
    source (0.0025, 0.001, 0.07). Not a reuse of Pendulum, CartPole, or Acrobot.
    """
    rows = ((0.0035, 0.0006, 0.075), (0.0025, 0.0013, 0.07), (0.0015, 0.0013, 0.085))
    return tuple(
        _mountaincar(
            f"mountaincar_look_dev{i}",
            "lookahead_dev",
            f"Lookahead versus H=16 development gravity/force/speed {row}.",
            gravity=row[0],
            force=row[1],
            max_speed=row[2],
        )
        for i, row in enumerate(rows)
    )
