"""MountainCarContinuous-v0 family with discretized force and dense height.

Not MountainCar-v0, Pendulum, CartPole, or Acrobot. Gymnasium sparse +100 /
action-cost reward and goal termination are not used for the primary.
Discrete MountainCar checkpoints are not transferred.
"""
from __future__ import annotations

from nexus.tasks.spec import TaskSpec

MCC_OBS_DIM = 2
MCC_N_ACTIONS = 3
MCC_MAX_STEPS = 200


def _mcc(task_id: str, split: str, notes: str, **params: float) -> TaskSpec:
    return TaskSpec(
        task_id=task_id,
        family="mountaincar_continuous",
        gym_id="MountainCarContinuous-v0",
        obs_dim=MCC_OBS_DIM,
        n_actions=MCC_N_ACTIONS,
        params=params,
        reward_scale=1.0,
        train_split=split,
        notes=notes,
    )


def mcc_default() -> TaskSpec:
    return _mcc(
        "mcc_default",
        "source",
        "Source training task. Discretized force, dense valley height, 200-step TimeLimit, no goal termination.",
        gravity=0.0025,
        power=0.0015,
        max_speed=0.07,
    )


def mcc_physics_key(spec: TaskSpec) -> tuple[float, float, float]:
    p = spec.params
    return (
        round(float(p["gravity"]), 4),
        round(float(p["power"]), 4),
        round(float(p["max_speed"]), 3),
    )


def mcc_lookahead_development() -> tuple[TaskSpec, ...]:
    """Unused MountainCarContinuous physics for lookahead versus frozen H=16.

    Generated by locked rule `mcc_lookahead_dev_v1`. Rejects the default
    source (0.0025, 0.0015, 0.07). Not a reuse of discrete MountainCar.
    """
    rows = ((0.0038, 0.0019, 0.085), (0.0024, 0.0019, 0.09), (0.0033, 0.0014, 0.05))
    return tuple(
        _mcc(
            f"mcc_look_dev{i}",
            "lookahead_dev",
            f"Lookahead versus H=16 development gravity/power/speed {row}.",
            gravity=row[0],
            power=row[1],
            max_speed=row[2],
        )
        for i, row in enumerate(rows)
    )
